/**
 * Normalizes GeoJSON coordinates into arrays of { latitude, longitude } coordinate rings.
 * Returns an array of rings: Array<Array<{ latitude: number, longitude: number }>>.
 * If locality has no verified boundary geometry, returns an empty array.
 */
export function getLocalityBoundaryRings(locality) {
    if (!locality) return [];

    // 1. Check if the locality document carries explicit boundaryGeoJSON
    let geo = locality.boundaryGeoJSON || locality.boundary || null;

    // 2. Fall back to verified canonical municipal dataset if not in doc
    if (!geo) {
        const idKey = (locality.id || '').toLowerCase().replace(/-/g, '_');
        const nameKey = (locality.name || '').toLowerCase().replace(/\s+/g, '_');
        geo = VERIFIED_LOCALITY_BOUNDARIES[locality.id] ||
              VERIFIED_LOCALITY_BOUNDARIES[idKey] ||
              VERIFIED_LOCALITY_BOUNDARIES[nameKey] ||
              null;
    }

    if (!geo || !geo.coordinates) {
        return [];
    }

    const rings = [];

    if (geo.type === 'Polygon') {
        // coordinates: [ [ [lng, lat], ... ], ... ]
        if (Array.isArray(geo.coordinates) && geo.coordinates.length > 0) {
            const exterior = geo.coordinates[0];
            if (Array.isArray(exterior) && exterior.length > 2) {
                rings.push(
                    exterior.map((pt) => ({
                        latitude: Number(pt[1]),
                        longitude: Number(pt[0]),
                    }))
                );
            }
        }
    } else if (geo.type === 'MultiPolygon') {
        // coordinates: [ [ [ [lng, lat], ... ] ], ... ]
        if (Array.isArray(geo.coordinates)) {
            geo.coordinates.forEach((poly) => {
                if (Array.isArray(poly) && poly.length > 0) {
                    const exterior = poly[0];
                    if (Array.isArray(exterior) && exterior.length > 2) {
                        rings.push(
                            exterior.map((pt) => ({
                                latitude: Number(pt[1]),
                                longitude: Number(pt[0]),
                            }))
                        );
                    }
                }
            });
        }
    }

    return rings;
}

/**
 * Checks if a locality has verified boundary geometry.
 */
export function hasLocalityBoundary(locality) {
    const rings = getLocalityBoundaryRings(locality);
    return rings && rings.length > 0;
}
